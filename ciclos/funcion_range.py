# Funcion range en python usada para iteraciones en ciclos python 
print(" Funcion in range ")
print("Secuencia del 0 al 4: ")
# iniciio es 0
# fin = 5-1
# incremento  = 1 
for i in range(5): #fn = 5-1
    print(i, end=' ')

print("\nSecuencia del 10 al 20: ")
for i in range(10,21):
    print(i,end=' ')