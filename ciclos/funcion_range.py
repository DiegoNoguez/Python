# Funcion range en python usada para iteraciones en ciclos python 
print(" Funcion in range ")
print("Secuencia del 0 al 4: ")
# iniciio es 0 opcional 
# fin = 5-1
# incremento  = 1  opcional
for i in range(5): #fn = 5-1
    print(i, end=' ')

print("\nSecuencia del 10 al 20: ")
# incremento no dado por lo tanto es en 1 en 1 
for i in range(10,21):
    print(i,end=' ')

print("\n\nSecuencia del 10 al 30 de 2 en 2: ")
for i in range(20,31,2):
    print(i, end=' ')