# Uso de las funciones bool y falsy en python con estas fucniones
# y como usarlos con ejemplos 

# Funcion bool 
print(f"valor 0: {bool(0)}") # Es considerado falsa y si es 1 true 
print(f"valor 0: {bool(1)}")

print(f"valor '':{bool('')}") # cadena vacia es falso
print(f"valor 'HOLa:{bool('Hola')}") # cadena con caraccteres es true 

print(f"Valor none: {bool(None)}") # Recibira o dara un falseya que se considera ausencia de valor


