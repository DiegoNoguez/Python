# Conversion de tipos de datos en python 

numeroString = "25"

# Convertir la cadena a tipo entero
numeroEntero = int(numeroString)
print(numeroString)
print(numeroEntero)

# Conversion de un nuemero entero a float 
numeroFlotante = float(numeroEntero)
print(numeroFlotante)

# Conversion de tipo flotante a string
numeroTexto = str(numeroFlotante)
print(numeroTexto)