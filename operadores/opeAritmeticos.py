# Operadores aritmeticos 
a = 10
b = 5

# Suma 
suma = a + b
 
# Resta
resta = a - b

# Multiplicacion
multi = a * b

# Division
div = a / b

# Division entera
divEn = a // b

# modulo 
modulo = a % b

# Exponente
exponente = a ** b
# Resultados 
print(f'EL resultado de la suma es: {suma}')
print(f'EL resultado de la resta es: {resta}')
print(f'EL resultado de la multipliación es: {multi}')
print(f'EL resultado de la divison es: {div}')
print(f'EL resultado de la Divion Entera es: {divEn}')
print(f'EL resultado de la Residuo de la división es: {modulo}')
print(f'EL resultado de la Exponente o potencia es: {exponente}')