# operadores de comparacion y algunos ejemplso
a,b = 7, 5

# impresion de valores inicioales 
print(f'Valor inicial de a: {a}, b: {b}')

# OPerador de igualdad ==
reulstado = a==b 
print(f'Resultado de a==b es: {reulstado}')

# OPerador diferente !=
reulstado = a!=b
print(f'A es distinto de b {reulstado}')

