# Conversion de una cadena de minusculas a mayusculas y viceversa
# con el metodo upper
frase= 'hola, soy springy, y tu?'

# forma de hacerlo con dos variables 
mayus = frase.upper()
print(mayus)

# forma directa
print(frase.upper())

# conversion a minuscula  con la funcion lower
print(mayus.lower())